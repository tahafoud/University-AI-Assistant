def _generate_pool(intent: str) -> List[str]:
    pool: List[str] = []
    if intent == "greeting":
        for g in _GREETS:
            for a in _GREET_ADDR:
                for t in _GREET_TAIL:
                    pool.append(" ".join(x for x in (g, a, t) if x))
    elif intent == "goodbye_thanks":
        for w in _THANKS:
            for t in _THANKS_TAIL:
                pool.append(" ".join(x for x in (w, t) if x))
        for w in _BYE:
            for t in _BYE_TAIL:
                pool.append(" ".join(x for x in (w, t) if x))
    else:
        for t in TOPICS.get(intent, []):
            pool += [f.format(t=t) for f in INFO_FRAMES]
        for a in ACTIONS.get(intent, []):
            pool += [f.format(a=a) for f in ACTION_FRAMES]
    return pool


def _norm(text: str) -> str:
    return clean_arabic_text(text, level="nlp")


MAX_NORM_LEN = 60  # model max_len is 64 chars; keep phrases fully visible


def build_splits(val_ratio: float = 0.3, aug_per_seed: int = 18,
                 template_cap: int = 320, seed: int = 42):
    """
    Returns (labels, train, val) exactly like before (train.py is unchanged).
      val   = held-out HAND-WRITTEN seed phrases only
      train = remaining seeds (+aug) + template phrases (+aug)
    """
    rng = random.Random(seed)
    labels = sorted(ALL_SEEDS.keys())

    # pass 1: split seeds for every intent, remember validation phrases
    seed_train: Dict[str, List[str]] = {}
    val: List[Tuple[str, int]] = []
    val_norm = set()
    for idx, name in enumerate(labels):
        phrases = ALL_SEEDS[name][:]
        rng.shuffle(phrases)
        n_val = max(3, int(len(phrases) * val_ratio))
        for p in phrases[:n_val]:
            val.append((p, idx))
            val_norm.add(_norm(p))
        seed_train[name] = phrases[n_val:]

    # pass 2: build training data (never containing a validation phrase)
    train: List[Tuple[str, int]] = []
    seen = set()

    def add(text: str, idx: int):
        n = _norm(text)
        if not n or len(n) > MAX_NORM_LEN or n in val_norm or (n, idx) in seen:
            return False
        seen.add((n, idx))
        train.append((text, idx))
        return True

    for idx, name in enumerate(labels):
        # hand-written seeds + augmented copies
        for p in seed_train[name]:
            add(p, idx)
            made = 0
            for _ in range(aug_per_seed * 4):
                if made >= aug_per_seed:
                    break
                if add(augment(p, name, rng), idx):
                    made += 1
        # template phrases (capped per class to keep classes balanced)
        pool = list(dict.fromkeys(_generate_pool(name)))
        rng.shuffle(pool)
        taken = 0
        for t in pool:
            if taken >= template_cap:
                break
            text = augment(t, name, rng) if rng.random() < 0.5 else t
            if add(text, idx):
                taken += 1

    rng.shuffle(train)
    return labels, train, val


