def _typo(word: str, rng: random.Random) -> str:
    if len(word) < 4:
        return word
    i = rng.randrange(1, len(word) - 1)
    op = rng.choice(["drop", "swap", "dup", "similar"])
    if op == "drop":
        return word[:i] + word[i + 1:]
    if op == "swap":
        return word[:i] + word[i + 1] + word[i] + word[i + 2:]
    if op == "dup":
        return word[:i] + word[i] + word[i:]
    ch = word[i]
    return word[:i] + _SIMILAR.get(ch, ch) + word[i + 1:]


def augment(text: str, intent: str, rng: random.Random) -> str:
    words = text.split()
    if not words:
        return text
    # 1) dialect swap
    if rng.random() < 0.30:
        for i, w in enumerate(words):
            if w in _DIALECT:
                words[i] = rng.choice(_DIALECT[w])
                break
    # 2) word dropout
    if len(words) > 3 and rng.random() < 0.20:
        words.pop(rng.randrange(len(words)))
    # 3) typos (1-2 words)
    if rng.random() < 0.50:
        for _ in range(rng.choice([1, 1, 2])):
            k = rng.randrange(len(words))
            words[k] = _typo(words[k], rng)
    # 4) elongation: "شكراااا", "متىىى"
    if rng.random() < 0.05:
        k = rng.randrange(len(words))
        words[k] = words[k] + words[k][-1] * rng.choice([1, 2, 3])
    # 5) missing space between two words
    if len(words) > 2 and rng.random() < 0.04:
        k = rng.randrange(len(words) - 1)
        words[k:k + 2] = [words[k] + words[k + 1]]
    out = " ".join(words)
    # 6) fillers / student-context prefixes
    if intent not in _NO_FILLER:
        if rng.random() < 0.35:
            out = rng.choice(_PREFIX) + " " + out
        if rng.random() < 0.30:
            out = out + " " + rng.choice(_SUFFIX)
    # 7) question mark noise
    r = rng.random()
    if r < 0.12 and not out.endswith("؟"):
        out += "؟"
    elif r > 0.94:
        out = out.replace("؟", "")
    return out.strip()


